library IEEE;
use IEEE.STD_LOGIC_1164.ALL;
use IEEE.NUMERIC_STD.ALL;

entity TB_ALU_4 is
end TB_ALU_4;

architecture test_arch of TB_ALU_4 is
    component ALU_4
        Port (
            A       : in  STD_LOGIC_VECTOR(7 downto 0);
            B       : in  STD_LOGIC_VECTOR(7 downto 0);
            ALU_Sel : in  STD_LOGIC_VECTOR(2 downto 0);
            Result  : out STD_LOGIC_VECTOR(7 downto 0);
            N       : out STD_LOGIC;
            Z       : out STD_LOGIC;
            V       : out STD_LOGIC;
            C       : out STD_LOGIC
        );
    end component;

    signal A, B       : STD_LOGIC_VECTOR(7 downto 0) := (others => '0');
    signal ALU_Sel    : STD_LOGIC_VECTOR(2 downto 0) := (others => '0');
    signal Result     : STD_LOGIC_VECTOR(7 downto 0);
    signal N, Z, V, C : STD_LOGIC;

begin
    DUT: ALU_4 port map(A=>A, B=>B, ALU_Sel=>ALU_Sel,
                        Result=>Result, N=>N, Z=>Z, V=>V, C=>C);
    STIMULUS: process
    begin
        ----------------------------------------------------------------
        -- SUMA 1: 0+0=0 ? Z=1
        ----------------------------------------------------------------
        ALU_Sel<="000"; A<="00000000"; B<="00000000"; wait for 20 ns;

        ----------------------------------------------------------------
        -- SUMA 2: (-5)+(-3)=-8 ? N=1
        ----------------------------------------------------------------
        ALU_Sel<="000"; A<="11111011"; B<="11111101"; wait for 20 ns;

        ----------------------------------------------------------------
        -- SUMA 3: 127+1 ? V=1
        ----------------------------------------------------------------
        ALU_Sel<="000"; A<="01111111"; B<="00000001"; wait for 20 ns;

        ----------------------------------------------------------------
        -- SUMA 4: 200+100=300 ? C=1
        ----------------------------------------------------------------
        ALU_Sel<="000"; A<="11001000"; B<="01100100"; wait for 20 ns;

        ----------------------------------------------------------------
        -- RESTA 1: 5-5=0 ? Z=1
        ----------------------------------------------------------------
        ALU_Sel<="001"; A<="00000101"; B<="00000101"; wait for 20 ns;

        ----------------------------------------------------------------
        -- RESTA 2: 3-10=-7 ? N=1, C=1
        ----------------------------------------------------------------
        ALU_Sel<="001"; A<="00000011"; B<="00001010"; wait for 20 ns;

        ----------------------------------------------------------------
        -- RESTA 3: (-128)-1 ? V=1
        ----------------------------------------------------------------
        ALU_Sel<="001"; A<="10000000"; B<="00000001"; wait for 20 ns;

        ----------------------------------------------------------------
        -- RESTA 4: 0-1 ? C=1
        ----------------------------------------------------------------
        ALU_Sel<="001"; A<="00000000"; B<="00000001"; wait for 20 ns;

        wait;
    end process;
end test_arch;